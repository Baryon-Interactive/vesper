#!/usr/bin/env python3
"""Write docs/third-party-licenses.md from the production dependency graph.

Rust: `cargo tree -e normal --target all` for the workspace and the launcher.
npm: production dependencies of the launcher frontend (`npm ls --omit=dev`).
The gateway has no production npm dependencies. Development and build tools are
excluded. Exits non-zero on a license expression that is not reviewed below.
Usage: python scripts/third-party-licenses.py [--check]
"""
import hashlib
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "third-party-licenses.md"
# Licenses compatible with distributing Vesper under Apache-2.0.
ALLOWED = {
    "MIT", "Apache-2.0", "Apache-2.0 WITH LLVM-exception", "BSD-2-Clause", "BSD-3-Clause",
    "ISC", "Zlib", "Unicode-3.0", "Unlicense", "0BSD", "BSL-1.0", "CC0-1.0",
    "CDLA-Permissive-2.0", "MPL-2.0",
}


def acceptable(expr: str) -> bool:
    """True when some OR alternative uses only allowed licenses (AND binds tighter)."""
    tokens = re.findall(r"\(|\)|[A-Za-z0-9.+-]+(?: WITH [A-Za-z0-9.+-]+)?", expr.replace("/", " OR "))
    pos = 0

    def parse_or():
        nonlocal pos
        ok = parse_and()
        while pos < len(tokens) and tokens[pos] == "OR":
            pos += 1
            ok = parse_and() or ok
        return ok

    def parse_and():
        nonlocal pos
        ok = parse_atom()
        while pos < len(tokens) and tokens[pos] == "AND":
            pos += 1
            ok = parse_atom() and ok
        return ok

    def parse_atom():
        nonlocal pos
        token = tokens[pos]
        pos += 1
        if token == "(":
            ok = parse_or()
            pos += 1  # ")"
            return ok
        return token in ALLOWED

    return bool(tokens) and parse_or() and pos == len(tokens)


def run(args, cwd=ROOT):
    return subprocess.run(args, cwd=cwd, check=True, capture_output=True, text=True, encoding="utf-8").stdout


def rust(manifest: str):
    out = run(["cargo", "tree", "--manifest-path", manifest, "-e", "normal", "--target", "all",
               "--prefix", "none", "--format", "{p}|{l}"])
    found = {}
    for line in out.splitlines():
        line = line.replace(" (*)", "")
        if "|" not in line:
            continue
        package, license_ = line.rsplit("|", 1)
        if "(" in package and ("\\" in package or "/" in package):
            continue  # workspace member or other path dependency
        name, version = package.split()[:2]
        found.setdefault(name, {})[version.lstrip("v")] = license_.strip() or "NONE"
    return found


def npm(prefix: str):
    data = json.loads(run([shutil.which("npm") or "npm", "ls", "--omit=dev", "--all", "--json"], cwd=ROOT / prefix))
    found = {}

    def walk(deps):
        for name, info in (deps or {}).items():
            pkg = ROOT / prefix / "node_modules" / name / "package.json"
            license_ = json.loads(pkg.read_text(encoding="utf-8")).get("license", "NONE") if pkg.exists() else "NONE"
            found.setdefault(name, {})[info.get("version", "?")] = str(license_)
            walk(info.get("dependencies"))

    walk(data.get("dependencies"))
    return found


def sha(path: str) -> str:
    return hashlib.sha256((ROOT / path).read_bytes()).hexdigest()


def table(found):
    rows = ["| Package | Version(s) | SPDX license expression |", "|---|---|---|"]
    for name in sorted(found, key=str.lower):
        versions = found[name]
        licenses = sorted(set(versions.values()))
        rows.append(f"| {name} | {', '.join(sorted(versions))} | {' ; '.join(licenses)} |")
    return rows


def main() -> int:
    groups = {
        "Rust: workspace crates (CLI and libraries)": rust("Cargo.toml"),
        "Rust: desktop launcher": rust("launcher/src-tauri/Cargo.toml"),
        "npm: launcher frontend": npm("launcher"),
    }
    bad = sorted({(n, l) for g in groups.values() for n, vs in g.items() for l in vs.values() if not acceptable(l)})
    if bad:
        print("Unreviewed license expressions:", file=sys.stderr)
        for name, license_ in bad:
            print(f"  {name}: {license_}", file=sys.stderr)
        return 1
    total = sum(len(g) for g in groups.values())
    lines = [
        "# Third-party production licenses",
        "",
        "Generated by `python scripts/third-party-licenses.py` from `cargo tree -e normal --target all`",
        "(workspace and launcher) and `npm ls --omit=dev` (launcher frontend). Development and build",
        "tools are excluded; the gateway has no production npm dependencies.",
        f"Cargo.lock SHA-256: `{sha('Cargo.lock')}`.",
        f"launcher/src-tauri/Cargo.lock SHA-256: `{sha('launcher/src-tauri/Cargo.lock')}`.",
        f"launcher/package-lock.json SHA-256: `{sha('launcher/package-lock.json')}`.",
        "",
        f"All {total} package records have a license expression with at least one alternative made only of",
        "Apache-2.0-compatible licenses (" + ", ".join(sorted(ALLOWED)) + ").",
        "MPL-2.0 is file-level copyleft: modified MPL files must stay under MPL-2.0.",
        "Preserve upstream copyright, license and notice files when redistributing dependencies; Vesper's",
        "license does not replace them. The generator fails on an unreviewed license expression. Re-run it",
        "after dependency or lockfile changes and review the diff.",
    ]
    for title, found in groups.items():
        lines += ["", f"## {title}", ""] + table(found)
    text = "\n".join(lines) + "\n"
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("docs/third-party-licenses.md is out of date; run python scripts/third-party-licenses.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({total} packages)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
